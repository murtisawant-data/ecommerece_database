USE ECOM; -- using the database

--  creating tables
-- customers
CREATE TABLE CUSTOMER(
CUST_ID varchar(255),
FIRST_NAME varchar(250),
LAST_NAME VARCHAR(255),
EMAIL varchar(250),
GENDER ENUM("MALE","FEMALE","OTHERS"),
PHONE varchar(10), 
ANNUAL_INCOME DECIMAL(10,2));
SELECT * FROM CUSTOMER;

DESCRIBE CUSTOMER;


CREATE TABLE PRODUCT(
PROD_ID INT PRIMARY KEY,
PROD_NAME VARCHAR(255) UNIQUE,
UNIT_PRICE DECIMAL(10,2),
CATEGORY VARCHAR(200));

ALTER TABLE CUSTOMER
MODIFY COLUMN CUST_ID VARCHAR(255)PRIMARY KEY;

DESCRIBE CUSTOMER;


CREATE TABLE SALES(
QUANTITY INT,
SALES DECIMAL(9,2),
CUSTOMER_ID VARCHAR(200),
PROD_ID INT,
DISCOUNT DECIMAL(3,2),
LOCATION CHAR(50),
ORDER_DATE DATE,
DELIVERY_DATE DATE,
PROFIT DECIMAL(9,2));

ALTER TABLE SALES
ADD CONSTRAINT FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER(CUST_ID),
ADD CONSTRAINT FOREIGN KEY (PROD_ID) REFERENCES PRODUCT(PROD_ID);
DESCRIBE SALES;

